"""Turns the pixel-art PNGs in assets/surface/ into pixelfx/src/fx/creature/surface-sprites.js.

Usage: python3 tools/sprites.py        (needs Pillow)

A file's name says what it is: tree-*.png are trees, rock-*.png are rocks. The art must be on a 1 px grid
(one pixel of the file = one pixel of the scene). A fake transparency checkerboard (light greys) around the
sprite is removed by flooding from the edges; real alpha works too. Each colour gets a role (outline, leaf,
trunk, stone) and a level (its rank by brightness within the role), so the effect can recolour the sprite
with the scene's own colours.
"""
import colorsys, json, os, sys
from collections import deque
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC, OUT = os.path.join(ROOT, "assets", "surface"), os.path.join(ROOT, "pixelfx", "src", "fx", "creature", "surface-sprites.js")
CHARS = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"

def checker(c):
    return c[3] > 0 and min(c[:3]) > 195 and max(c[:3]) - min(c[:3]) < 8

def load(path):
    im = Image.open(path).convert("RGBA"); W, H = im.size; px = im.load()
    q, seen = deque(), set()
    for x in range(W): q.extend([(x, 0), (x, H - 1)])
    for y in range(H): q.extend([(0, y), (W - 1, y)])
    while q:
        x, y = q.popleft()
        if (x, y) in seen or not (0 <= x < W and 0 <= y < H): continue
        seen.add((x, y))
        c = px[x, y]
        if c[3] == 0 or checker(c):
            px[x, y] = (0, 0, 0, 0); q.extend([(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)])
    if not stone_name(path):  # checker pixels caught inside a tree are holes in the leaves (a rock keeps its greys)
        for y in range(H):
            for x in range(W):
                if checker(px[x, y]): px[x, y] = (0, 0, 0, 0)
    for y in range(H):
        for x in range(W):
            if px[x, y][3] < 128: px[x, y] = (0, 0, 0, 0)
            else: px[x, y] = px[x, y][:3] + (255,)
    return im.crop(im.getbbox())

def stone_name(path):
    return os.path.basename(path).startswith("rock")

def role(c, kind):
    r, g, b = (v / 255 for v in c[:3]); h, l, s = colorsys.rgb_to_hls(r, g, b)
    if l < 0.09: return "line"
    if kind == "rock": return "stone"
    if s > 0.2 and 0.17 < h < 0.5: return "leaf"
    if s > 0.15 and (h < 0.13 or h > 0.95): return "wood"
    return "leaf" if g >= r else "wood"

sprites = {"tree": [], "rock": []}
for name in sorted(os.listdir(SRC)):
    if not name.endswith(".png"): continue
    kind = name.split("-")[0]
    if kind not in sprites: print("skip", name, "(name it tree-*.png or rock-*.png)"); continue
    im = load(os.path.join(SRC, name)); W, H = im.size; px = im.load()
    pal = sorted({px[x, y] for y in range(H) for x in range(W) if px[x, y][3]}, key=lambda c: sum(c[:3]))
    if len(pal) > len(CHARS): sys.exit(f"{name}: too many colours ({len(pal)})")
    roles = [role(c, kind) for c in pal]
    lum = lambda c: 0.299 * c[0] + 0.587 * c[1] + 0.114 * c[2]
    lvl = []
    for i, c in enumerate(pal):
        same = sorted(lum(d) for j, d in enumerate(pal) if roles[j] == roles[i])
        lvl.append(round(same.index(lum(c)) / max(1, len(same) - 1), 3))
    rows = ["".join(CHARS[pal.index(px[x, y])] if px[x, y][3] else "." for x in range(W)) for y in range(H)]
    sprites[kind].append({"name": name[:-4], "w": W, "h": H, "pal": ["#%02x%02x%02x" % c[:3] for c in pal], "role": roles, "lvl": lvl, "rows": rows})
    print(f"{name}: {W} x {H}, {len(pal)} colours, roles {dict((r, roles.count(r)) for r in set(roles))}")

with open(OUT, "w") as f:
    f.write("// Generated by tools/sprites.py from assets/surface/*.png: do not edit by hand.\n")
    f.write("// Pixel-art sprites for the planet surface, on a 1 px grid. rows: one char per pixel (palette index), '.' is clear.\n")
    f.write("// role/lvl: what each colour is (line, leaf, wood, stone) and its rank by brightness in that role (0 dark .. 1 light).\n")
    f.write("export const SPRITES = " + json.dumps(sprites, indent=1) + ";\n")
print("->", os.path.relpath(OUT, ROOT))
